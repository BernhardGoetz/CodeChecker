    fn scripted(
        structure: String,
        solutions: Vec<&'static str>,
        inputs: &'static str,
    ) -> impl Fn(&ChatRequest, usize) -> Result<String, AiError> + Sync {
        let counter = Mutex::new(0usize);
        move |r, _| {
            if is_structure(r) {
                Ok(structure.clone())
            } else if is_inputs(r) {
                Ok(inputs.to_string())
            } else {
                let mut c = counter.lock().unwrap();
                let s = solutions[*c % solutions.len()];
                *c += 1;
                Ok(program(s))
            }
        }
    }

