//! Test generation from a confirmed task text.
//!
//! Core rule: the model never writes expected outputs. It writes candidate
//! solutions and test inputs; expected outputs are the outputs of verified
//! solutions, executed in the sandbox (`runner::collect_outputs`).
//!
//! 1. Structure (JSON): input/output format, examples, comparison mode.
//!    Examples must appear verbatim in the task text, else they are dropped.
//! 2. N candidate solutions (temperature 0.7), precheck.
//! 3. Compile in the sandbox, at most one repair round with the compiler
//!    message.
//! 4. Run against the sheet's examples; failing solutions are dropped.
//! 5. Test inputs only (JSON array, at most 10).
//! 6. Majority vote: every surviving solution runs every input; outputs are
//!    grouped per comparison mode, the largest group gives the expectation.
//! 7. Confidence green / yellow / red; red yields no tests.
//!
//! The flow is generic over the model ([`Llm`]) and the sandbox
//! ([`Executor`]), so it is unit-tested with mocks.

