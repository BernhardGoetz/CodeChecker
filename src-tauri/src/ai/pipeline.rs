/// Whether the task reads input: the model's `readsInput`, else the input
/// format ("keine Eingabe", "none", "no input", empty count as no input).
/// Unclear means "reads input" (no empty test is forced then).
pub fn reads_input(s: &Structure) -> bool {
    if let Some(r) = s.reads_input {
        return r;
    }
    let f = s.input_format.trim().to_lowercase();
    let none = f.is_empty()
        || [
            "none",
            "no input",
            "nothing",
            "n/a",
            "keine",
            "kein",
            "ohne eingabe",
        ]
        .iter()
        .any(|k| f == *k || f.starts_with(&format!("{k} ")) || f.starts_with(&format!("{k}.")))
        || f.contains("no input")
        || f.contains("keine eingabe")
        || f.contains("does not read")
        || f.contains("reads nothing");
    !none
}

#[derive(Debug, Clone, Default, PartialEq, Deserialize)]
#[serde(default)]
pub struct Example {
    pub input: String,
    pub output: String,
}

/// Parses the model's JSON (tolerates text around the object).
pub fn parse_json<T: serde::de::DeserializeOwned>(answer: &str) -> Option<T> {
    if let Ok(v) = serde_json::from_str(answer.trim()) {
        return Some(v);
    }
    let start = answer.find('{')?;
    let end = answer.rfind('}')?;
    (end > start)
        .then(|| serde_json::from_str(&answer[start..=end]).ok())
        .flatten()
}

/// Mode suggested by the structure step.
pub fn suggested_mode(s: &Structure) -> Option<CompareMode> {
    match s.compare_mode.as_deref()? {
        "lines" => Some(CompareMode::Lines { trim: true }),
        "tokens" => Some(CompareMode::Tokens {
            case_sensitive: true,
        }),
        "float" => Some(CompareMode::Float {
            abs_tol: 1e-6,
            rel_tol: 1e-6,
        }),
        _ => None,
    }
}

pub use crate::runner::compare::normalize_for_match;

/// An example counts only if its output (non-empty) and its input appear
/// verbatim in the task text (after [`normalize_for_match`]).
pub fn example_in_text(normalized_text: &str, ex: &Example) -> bool {
    let input = normalize_for_match(&ex.input);
    let output = normalize_for_match(&ex.output);
    !output.is_empty() && normalized_text.contains(&output) && normalized_text.contains(&input)
}

/// Splits the model's examples into (verbatim, discarded count); at most
/// [`MAX_EXAMPLES`], duplicates removed.
pub fn verify_examples(task_text: &str, examples: &[Example]) -> (Vec<Example>, usize) {
    let text = normalize_for_match(task_text);
    let mut kept: Vec<Example> = Vec::new();
    let mut discarded = 0;
    for ex in examples {
        if !example_in_text(&text, ex) {
            discarded += 1;
            continue;
        }
        let dup = kept.iter().any(|k| {
            normalize_for_match(&k.input) == normalize_for_match(&ex.input)
                && normalize_for_match(&k.output) == normalize_for_match(&ex.output)
        });
        if !dup && kept.len() < MAX_EXAMPLES {
            kept.push(ex.clone());
        }
    }
    (kept, discarded)
}

/// Safety net against placeholder templates extracted as examples (a
/// placeholder must never become an expected output). Independent of the
/// input, an example is dropped if its output
/// - contains a placeholder token of an accepted template (word boundary),
/// - or fits a template as a whole.
///
/// Returns the kept examples and the number dropped.
pub fn drop_template_examples(
    examples: Vec<Example>,
    templates: &[OutputTemplate],
) -> (Vec<Example>, usize) {
    if templates.is_empty() {
        return (examples, 0);
    }
    let before = examples.len();
    let kept: Vec<Example> = examples
        .into_iter()
        .filter(|e| {
            let has_placeholder = templates
                .iter()
                .flat_map(|t| &t.placeholders)
                .any(|p| template::contains_token(&e.output, p));
            let is_template = templates
                .iter()
                .any(|t| normalize_for_match(&t.text) == normalize_for_match(&e.output));
            !(has_placeholder || is_template)
        })
        .collect();
    let dropped = before - kept.len();
    (kept, dropped)
}

/// Whether an output fits the output templates (always without templates).
pub fn fits_templates(templates: &[OutputTemplate], o: &StepOutput) -> bool {
    template::check_output(templates, &o.stdout).is_none()
}

