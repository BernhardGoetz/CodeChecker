    #[test]
    fn confidence_levels() {
        let base = Evidence {
            solutions: 5,
            compiled: 5,
            survivors: 4,
            examples: 2,
            tests: 8,
            dropped: 0,
            min_agreement: Some(1.0),
            ..Evidence::default()
        };
        assert_eq!(decide_confidence(&base).level, ConfidenceLevel::Green);
        // 2 of 3 agree, no examples: yellow, the disagreement is named.
        let c = decide_confidence(&Evidence {
            solutions: 3,
            compiled: 3,
            survivors: 3,
            examples: 0,
            tests: 1,
            min_agreement: Some(2.0 / 3.0),
            ..base.clone()
        });
        assert_eq!(c.level, ConfidenceLevel::Yellow);
        assert!(c.reasons.iter().any(|r| r.contains("keine Beispiele")));
        assert!(
            c.reasons.iter().any(|r| r.contains("knapp einig (67 %)")),
            "{c:?}"
        );
        // 4 of 5 agree with examples: green.
        let c = decide_confidence(&Evidence {
            min_agreement: Some(0.8),
            ..base.clone()
        });
        assert_eq!(c.level, ConfidenceLevel::Green);
        // Template fallback: yellow; template mismatch without tests: red.
        let c = decide_confidence(&Evidence {
            template_fallback: true,
            ..base.clone()
        });
        assert_eq!(c.level, ConfidenceLevel::Yellow);
        assert!(c.reasons.iter().any(|r| r == TEMPLATE_FALLBACK_REASON));
        let c = decide_confidence(&Evidence {
            tests: 0,
            template_mismatch: true,
            ..base.clone()
        });
        assert_eq!(c.level, ConfidenceLevel::Red);
        assert_eq!(c.reasons, vec![TEMPLATE_MISMATCH_REASON.to_string()]);
        let c = decide_confidence(&Evidence {
            min_agreement: Some(0.75),
            ..base.clone()
        });
        assert_eq!(c.level, ConfidenceLevel::Yellow);
        assert!(c.reasons[0].contains("75 %"), "{:?}", c.reasons);
        let c = decide_confidence(&Evidence {
            examples: 0,
            ..base.clone()
        });
        assert_eq!(c.level, ConfidenceLevel::Yellow);
        assert!(c.reasons[0].contains("keine Beispiele"));
        assert_eq!(
            decide_confidence(&Evidence {
                survivors: 1,
                ..base.clone()
            })
            .level,
            ConfidenceLevel::Yellow
        );
        assert_eq!(
            decide_confidence(&Evidence {
                dropped: 1,
                ..base.clone()
            })
            .level,
            ConfidenceLevel::Yellow
        );
        let c = decide_confidence(&Evidence {
            survivors: 0,
            ..base.clone()
        });
        assert_eq!(c.level, ConfidenceLevel::Red);
        assert!(c.reasons[0].contains("Beispiele des Aufgabenblatts"));
        let c = decide_confidence(&Evidence {
            survivors: 0,
            compiled: 0,
            ..base.clone()
        });
        assert!(c.reasons[0].contains("kompilieren"));
        assert_eq!(
            decide_confidence(&Evidence { tests: 0, ..base }).level,
            ConfidenceLevel::Red
        );
    }

