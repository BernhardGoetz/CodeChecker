    /// Scripted model: the answer is computed from the request and the
    /// number of earlier calls.
    struct MockLlm<F> {
        answer: F,
        /// One entry per answer (a request with `n` answers adds `n`).
        calls: Mutex<Vec<ChatRequest>>,
        /// Answers per request, in order.
        batches: Mutex<Vec<usize>>,
    }

    impl<F: Fn(&ChatRequest, usize) -> Result<String, AiError> + Sync> MockLlm<F> {
        fn new(answer: F) -> Self {
            Self {
                answer,
                calls: Mutex::new(Vec::new()),
                batches: Mutex::new(Vec::new()),
            }
        }
        fn calls(&self) -> Vec<ChatRequest> {
            self.calls.lock().unwrap().clone()
        }
        fn batches(&self) -> Vec<usize> {
            self.batches.lock().unwrap().clone()
        }
        fn answer(&self, req: &ChatRequest) -> Result<ChatResponse, AiError> {
            let n = {
                let mut c = self.calls.lock().unwrap();
                c.push(req.clone());
                c.len() - 1
            };
            (self.answer)(req, n).map(|content| ChatResponse {
                content,
                completion_tokens: Some(10),
                tokens_per_second: Some(20.0),
                finish_reason: Some("stop".into()),
                stopping_word: None,
                ..ChatResponse::default()
            })
        }
    }

    impl<F: Fn(&ChatRequest, usize) -> Result<String, AiError> + Sync> Llm for MockLlm<F> {
        async fn chat(&self, req: &ChatRequest) -> Result<ChatResponse, AiError> {
            self.batches.lock().unwrap().push(1);
            self.answer(req)
        }

        /// Like llama-server with `"n"`: one request, `n` answers, all
        /// together; one failing answer fails the request.
        async fn chat_n(&self, req: &ChatRequest, n: usize) -> Result<Vec<ChatResponse>, AiError> {
            self.batches.lock().unwrap().push(n);
            (0..n).map(|_| self.answer(req)).collect()
        }
    }

    fn step(stdout: &str, exit: i64) -> StepOutput {
        StepOutput {
            stdout: stdout.into(),
            stderr: String::new(),
            stdout_truncated: false,
            stderr_truncated: false,
            exit_code: Some(exit),
            timed_out: false,
            duration_ms: 1,
        }
    }

    /// Fake sandbox: the "program" is a keyword in the code.
    /// `double`/`triple`/`plus1` compute on the first integer of the input,
    /// `float` prints n/3 with 4 or 6 decimals, `crash` exits with 1,
    /// `SYNTAX` does not compile. Counts containers, compiles and runs.
    #[derive(Default)]
    struct Counters {
        opened: usize,
        closed: usize,
        compiles: usize,
        runs: usize,
    }

    struct MockExec {
        counters: Arc<Mutex<Counters>>,
        /// Sandbox error on the n-th compile (1-based).
        fail_compile: Option<usize>,
        /// Sandbox error on the n-th container start (1-based).
        fail_open: Option<usize>,
    }

    impl MockExec {
        fn new() -> Self {
            Self {
                counters: Arc::new(Mutex::new(Counters::default())),
                fail_compile: None,
                fail_open: None,
            }
        }
        fn get(&self) -> std::sync::MutexGuard<'_, Counters> {
            self.counters.lock().unwrap()
        }
    }

    struct MockSession {
        counters: Arc<Mutex<Counters>>,
        code: Mutex<String>,
        fail_compile: Option<usize>,
    }

    fn output_for(code: &str, input: &str) -> StepOutput {
        let n: i64 = input
            .split_whitespace()
            .next()
            .and_then(|t| t.parse().ok())
            .unwrap_or(0);
        if code.contains("crash") {
            step("", 1)
        } else if code.contains("double") {
            step(&format!("{}\n", n * 2), 0)
        } else if code.contains("triple") {
            step(&format!("{}\n", n * 3), 0)
        } else if code.contains("plus1") {
            step(&format!("{}\n", n + 1), 0)
        } else if code.contains("ergebnis") {
            // Reads a number: crashes without input (EOFError).
            if input.trim().is_empty() {
                step("", 1)
            } else {
                step(&format!("Ergebnis: {}\n", n * 2), 0)
            }
        } else if code.contains("prompt") {
            // input("Zahl eingeben: ") before reading; crashes without input.
            if input.trim().is_empty() {
                step("Zahl eingeben: ", 1)
            } else {
                step(&format!("Zahl eingeben: {}\n", n * 2), 0)
            }
        } else if code.contains("readstime") {
            // Reads „hour minute second“ (Scanner): crashes without input.
            if input.trim().is_empty() {
                step("", 1)
            } else {
                step(QAS_WRONG_OUTPUT, 0)
            }
        } else if code.contains("readsdefault") {
            // Reads input if there is some, else uses the given values.
            if input.trim().is_empty() {
                step(QAS_OUTPUT, 0)
            } else {
                step(QAS_WRONG_OUTPUT, 0)
            }
        } else if code.contains("wrongdiff") {
            step(QAS_WRONG_OUTPUT, 0)
        } else if code.contains("qasfloat") {
            step(QAS_FLOAT_OUTPUT, 0)
        } else if code.contains("qas") {
            step(QAS_OUTPUT, 0)
        } else if code.contains("secs") {
            step(SECS_OUTPUT, 0)
        } else if code.contains("badfmt") {
            step("54630\n31770\n", 0)
        } else if code.contains("float4") {
            step(&format!("{:.4}\n", n as f64 / 3.0), 0)
        } else if code.contains("float6") {
            step(&format!("{:.6}\n", n as f64 / 3.0), 0)
        } else {
            step("?\n", 0)
        }
    }

    impl Session for MockSession {
        async fn compile(&self, code: &str) -> Result<CompileOutcome, AiError> {
            let n = {
                let mut c = self.counters.lock().unwrap();
                c.compiles += 1;
                c.compiles
            };
            if self.fail_compile == Some(n) {
                return Err(AiError::Other("Fehler der Container-Engine: weg".into()));
            }
            *self.code.lock().unwrap() = code.to_string();
            if code.contains("SYNTAX") {
                return Ok(CompileOutcome {
                    output: Some(StepOutput {
                        stderr: "SyntaxError: invalid syntax".into(),
                        ..step("", 1)
                    }),
                    ok: false,
                });
            }
            Ok(CompileOutcome {
                output: Some(step("", 0)),
                ok: true,
            })
        }

        async fn run(&self, inputs: &[String]) -> Result<Vec<StepOutput>, AiError> {
            self.counters.lock().unwrap().runs += inputs.len();
            let code = self.code.lock().unwrap().clone();
            Ok(inputs.iter().map(|i| output_for(&code, i)).collect())
        }

        async fn close(self) {
            self.counters.lock().unwrap().closed += 1;
        }
    }

    impl Executor for MockExec {
        type Session = MockSession;

        async fn open(&self, _language: &str) -> Result<MockSession, AiError> {
            let n = {
                let mut c = self.counters.lock().unwrap();
                c.opened += 1;
                c.opened
            };
            if self.fail_open == Some(n) {
                // A container that failed to start needs no removal.
                self.counters.lock().unwrap().closed += 1;
                return Err(AiError::Other("Fehler der Container-Engine: Start".into()));
            }
            Ok(MockSession {
                counters: self.counters.clone(),
                code: Mutex::new(String::new()),
                fail_compile: self.fail_compile,
            })
        }
    }

    const TASK: &str = "Lies eine ganze Zahl n und gib 2·n aus.\n\nBeispiel:\nEingabe:\n  21\nAusgabe:\n  42\n\nEingabe: 5\nAusgabe: 10\n";

    fn structure_json(examples: &[(&str, &str)], mode: &str) -> String {
        let ex: Vec<serde_json::Value> = examples
            .iter()
            .map(|(i, o)| serde_json::json!({"input": i, "output": o}))
            .collect();
        serde_json::json!({
            "inputFormat": "eine Zahl n",
            "outputFormat": "2n",
            "examples": ex,
            "compareMode": mode
        })
        .to_string()
    }

    fn is_structure(r: &ChatRequest) -> bool {
        r.messages[0].content == prompts::STRUCTURE_SYSTEM
    }
    fn is_inputs(r: &ChatRequest) -> bool {
        r.messages[0].content == prompts::INPUTS_SYSTEM
    }
    fn is_repair(r: &ChatRequest) -> bool {
        r.messages.len() > 2 && r.messages[2].role == Role::Assistant
    }

    fn program(word: &str) -> String {
        format!("```python\n# {word}\nprint(int(input()) * 2)\n```")
    }

    /// Model answering with `solutions[i]` for the i-th solution request.
    fn scripted(
        structure: String,
        solutions: Vec<&'static str>,
        inputs: &'static str,
    ) -> impl Fn(&ChatRequest, usize) -> Result<String, AiError> + Sync {
        let counter = Mutex::new(0usize);
        move |r, _| {
            if is_structure(r) {
                Ok(structure.clone())
            } else if is_inputs(r) {
                Ok(inputs.to_string())
            } else {
                let mut c = counter.lock().unwrap();
                let s = solutions[*c % solutions.len()];
                *c += 1;
                Ok(program(s))
            }
        }
    }

    fn req(mode: Option<CompareMode>) -> GenerateRequest {
        GenerateRequest {
            task_text: TASK.into(),
            language: "python".into(),
            compare_mode: mode,
        }
    }

    fn settings(n: usize) -> Settings {
        Settings {
            solutions: n,
            repair_rounds: 1,
            speeds: None,
        }
    }

    fn block_on<F: Future>(f: F) -> F::Output {
        tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .unwrap()
            .block_on(f)
    }

    fn generate_with<F: Fn(&ChatRequest, usize) -> Result<String, AiError> + Sync>(
        llm: &MockLlm<F>,
        r: GenerateRequest,
        n: usize,
    ) -> Result<GenerateResult, AiError> {
        generate_with_llm(llm, r, n)
    }

    fn generate_with_llm(
        llm: &(impl Llm + Sync),
        r: GenerateRequest,
        n: usize,
    ) -> Result<GenerateResult, AiError> {
        let exec = MockExec::new();
        let token = CancellationToken::new();
        block_on(generate(llm, &exec, &r, settings(n), &token, |_| {}))
    }

