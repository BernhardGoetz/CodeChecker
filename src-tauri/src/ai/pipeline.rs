#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GenerateRequest {
    pub task_text: String,
    pub language: String,
    /// The user's comparison mode (wins over the model's suggestion).
    #[serde(default)]
    pub compare_mode: Option<CompareMode>,
}

impl GenerateRequest {
    /// Backend gate (the confirmation checkbox is the frontend gate).
    pub fn validate(&self) -> Result<&'static languages::LanguageConfig, AiError> {
        if self.task_text.trim().is_empty() {
            return Err(AiError::Other(
                "Die Aufgabenstellung ist leer – bitte zuerst den Aufgabentext einfügen.".into(),
            ));
        }
        let chars = self.task_text.chars().count();
        if chars > MAX_TASK_CHARS {
            return Err(AiError::Other(format!(
                "Die Aufgabenstellung ist zu lang für das KI-Modell ({chars} Zeichen, höchstens \
                 {MAX_TASK_CHARS}). Bitte auf die eigentliche Aufgabe kürzen."
            )));
        }
        if let Some(mode) = &self.compare_mode {
            mode.validate().map_err(AiError::Other)?;
        }
        languages::get(&self.language)
            .ok_or_else(|| AiError::Other(format!("Unbekannte Sprache: {}", self.language)))
    }
}

